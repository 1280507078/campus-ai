/* ==================================================================
   校内步行路网图（campus walking graph）
   ------------------------------------------------------------------
   ## 为什么需要它

   高德步行规划只认市政道路，校园内部的小路覆盖不全：有的路线会被带出
   校门绕一大圈（如知行楼到致远楼，实际 200 米它绕 1.7 公里）。

   解决：自己建一张「节点 + 边」的图，起终点都在校内时用 Dijkstra 算最短路。

   ## 数据从哪来（关键）

   **只取「底图上画出来的白色道路」**，不掺任何手画直线。

   为什么砍到只剩一个来源：判断一条路线好不好，唯一有意义的标准是
   「它是不是压在地图上那条白路上」。出错过两次，原因都是几何来源不干净：

     ✗ OpenStreetMap 的 footway/path/steps
       实测离高德底图路面 **80% 超过 4 m**（两边对不上），画出来就是"不在路上"。
     ✗ 高德步行规划密集探测（234 条折线，112.7 km）
       它自己很准（离白路 p90 = 0.00 m），但其中 6.5% 是**高德会走、地图不画**的
       路（未绘制的校园小径）。那部分画在图上同样"不在路上"，所以只用来补
       栅格没提取到的残段，最终只净贡献 0.07 km。

   最终几何 = 底图栅格提取 + 上述 0.07 km 补充。

   ## 管线（脚本在 gtest/，可复现）

     capture_grid.mjs     用 center+zoom 精确网格截 2×2 张干净底图（z19/dpr2，
                          roadshot.html 已关掉注记文字——注记是纯白字，会变假路）
     extract_roads2.py    纯白分割 → 骨架化 → 矢量化 → 抽稀。
                          实测这批折线离真实白路 **p50~p99 全 0.00 m**
     merge2.py            与高德探测折线去重影（沿线每 2 m 采样查覆盖）
     build_graph2.py      T 型接点插入 → 端点 2 m 聚类 → 建边 → 补接 → 跨隧道补桥
     qa_graph.py          ★ 硬指标：整张图离真实白路多远

   ## 两条实现约束

   1. **瓦片拼接必须用页面回报的 bounds。**
      旧 `tiles/meta.json` 记的是每块截图各自"重新居中"后的四角，拼出来是错位的
      （实测同排块左上角间距 1724~2522 px，应恒为 3200）。用那种底图提取的折线，
      中位离真实道路 3.06 m、p90 22.4 m。新 `capture_grid.mjs` 用精确网格 +
      回报 bounds，块间还留 ~10 m 重叠。

   2. **边的折线几何绝对不能丢。**
      旧建图把折线吸附到 2.5 m 网格后**只留节点对**，两节点之间永远是一条直线，
      弯路全被"抄近道"抹平。实测结果：48% 的节点离真实道路 >4 m，
      **56% 的总里程离路 >4 m**（最差 174 m）—— 用户在手机上看到的就是"根本没在路上"。
      现在每条边都带 `via` 中间点，`edgePoints()` 会把它们串起来。

   ## 质量（qa_graph.py，基准 = 单张整屏标定底图）

     采样点离最近白色道路：p50 0.00 / p75 0.00 / **p90 0.00** / p95 4.28 / p99 13.49 m
     **离路 >3 m 的里程占比 5.6%**（其中一多半是跨断口补的 6 条桥 ——
      那几段被高架盖住，必然看不到白路）

   ## 数据结构

     CAMPUS_GRAPH = {
       nodes: { v0: {lng, lat[, name]}, ... },
       edges: [ [a, b], [a, b, [[lng,lat],...]], ... ]
     }
     edges: [a, b]                      a-b 是一段真实道路折线段
     edges: [a, b, [[lng,lat], ...]]    a->b 中间还有这些顶点（**必须照这些点画**）
   ================================================================== */

