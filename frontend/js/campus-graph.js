/** 「途径某地标」的判定半径（米）：路线离它 45 米内就算路过 */
const LANDMARK_TOL = 45;

/* ==================================================================
   路网计算工具（Dijkstra 最短路 + 道路段投影吸附）
   ================================================================== */

/** 地球半径（米），球面距离计算用 */
const EARTH_R = 6371000;

/**
 * 两点球面距离（米）。haversine 公式，校园尺度下误差可忽略。
 */
function haversine(lng1, lat1, lng2, lat2) {
  const rad = Math.PI / 180;
  const dLat = (lat2 - lat1) * rad;
  const dLng = (lng2 - lng1) * rad;
  const a = Math.sin(dLat / 2) ** 2 +
    Math.cos(lat1 * rad) * Math.cos(lat2 * rad) * Math.sin(dLng / 2) ** 2;
  return 2 * EARTH_R * Math.asin(Math.sqrt(a));
}

/** 一条边的完整折线，返回 [[lng,lat],...]（点串边就是两端点） */
function edgePoints(e) {
  const a = CAMPUS_GRAPH.nodes[e[0]], b = CAMPUS_GRAPH.nodes[e[1]];
  const via = (e[2] || []).map(p => [p[0], p[1]]);
  return [[a.lng, a.lat], ...via, [b.lng, b.lat]];
}

/** 一条边的实际长度（米） */
function edgeLength(e) {
  const pts = edgePoints(e);
  let sum = 0;
  for (let i = 1; i < pts.length; i++) {
    sum += haversine(pts[i - 1][0], pts[i - 1][1], pts[i][0], pts[i][1]);
  }
  return sum;
}

/** 校园范围框（含全部节点再放宽一点），用于判断「起终点是否在校内」 */
const CAMPUS_BBOX = (() => {
  let w = 999, e = -999, s = 999, n = -999;
  Object.values(CAMPUS_GRAPH.nodes).forEach(p => {
    w = Math.min(w, p.lng); e = Math.max(e, p.lng);
    s = Math.min(s, p.lat); n = Math.max(n, p.lat);
  });
  const pad = 0.002;   // 约 220 米余量：紧邻校门的点位也算「校内可达」
  return { w: w - pad, e: e + pad, s: s - pad, n: n + pad };
})();

/** 坐标是否落在校园范围框内 */
function inCampus(lng, lat) {
  return lng >= CAMPUS_BBOX.w && lng <= CAMPUS_BBOX.e &&
         lat >= CAMPUS_BBOX.s && lat <= CAMPUS_BBOX.n;
}

/**
 * 把点 P 投影到线段 A->B 上（校园尺度按平面近似，经度乘 cos(lat) 修正）。
 * @returns {{pt:number[], d:number, t:number}} pt=投影点, d=距离(米), t∈[0,1]
 */
function projectToSeg(px, py, a, b) {
  const kx = Math.cos(py * Math.PI / 180);       // 经度->米的缩放
  const ax = a[0] * kx, bx = b[0] * kx, px2 = px * kx;
  const dx = bx - ax, dy = b[1] - a[1];
  const len2 = dx * dx + dy * dy;
  let t = len2 ? ((px2 - ax) * dx + (py - a[1]) * dy) / len2 : 0;
  t = Math.max(0, Math.min(1, t));
  const pt = [a[0] + (b[0] - a[0]) * t, a[1] + (b[1] - a[1]) * t];
  return { pt, d: haversine(px, py, pt[0], pt[1]), t };
}

/** 离某坐标最近的路网节点（调试图层用）。 */
function nearestNode(lng, lat) {
  let best = null, bestD = Infinity;
  for (const [id, p] of Object.entries(CAMPUS_GRAPH.nodes)) {
    const d = haversine(lng, lat, p.lng, p.lat);
    if (d < bestD) { bestD = d; best = id; }
  }
  return { id: best, dist: bestD };
}

/** 邻接表：id -> [{to, edge, len, pts}]（边双向可用，pts 是「从这个节点出发」方向的折线） */
const ADJ = (() => {
  const adj = {};
  Object.keys(CAMPUS_GRAPH.nodes).forEach(id => { adj[id] = []; });
  CAMPUS_GRAPH.edges.forEach(e => {
    const [a, b] = e;
    const len = edgeLength(e);
    const pts = edgePoints(e);
    adj[a].push({ to: b, edge: e, len, pts });
    adj[b].push({ to: a, edge: e, len, pts: pts.slice().reverse() });
  });
  return adj;
})();

/**
 * Dijkstra：图上两节点间最短路。
 * @param {object} [adj=ADJ] 邻接表（吸附时会临时加虚拟起终点 F/T）
 * @returns {{nodePath: string[], edgePath: Array, meters: number}|null}
 */
function dijkstra(src, dst, adj) {
  adj = adj || ADJ;
  if (!adj[src] || !adj[dst]) return null;
  const dist = {}, prev = {}, prevEdge = {}, visited = {};
  Object.keys(adj).forEach(id => { dist[id] = Infinity; });
  dist[src] = 0;

  while (true) {
    let u = null, du = Infinity;
    for (const id in dist) {
      if (!visited[id] && dist[id] < du) { u = id; du = dist[id]; }
    }
    if (u === null || u === dst) break;
    visited[u] = true;

    for (const { to, edge, len } of adj[u]) {
      if (visited[to]) continue;
      const nd = dist[u] + len;
      if (nd < dist[to]) { dist[to] = nd; prev[to] = u; prevEdge[to] = edge; }
    }
  }

  if (!isFinite(dist[dst])) return null;

  const nodePath = [dst], edgePath = [];
  let cur = dst;
  while (cur !== src) {
    edgePath.unshift(prevEdge[cur]);
    nodePath.unshift(prev[cur]);
    cur = prev[cur];
  }
  return { nodePath, edgePath, meters: Math.round(dist[dst]) };
}

/** 取折线的一段：从第 f.segIdx 段上的 f.pt 走到第 t.segIdx 段上的 t.pt（同向） */
function slicePoly(pts, f, t) {
  const out = [f.pt];
  for (let i = f.segIdx; i <= t.segIdx - 1; i++) out.push(pts[i]);
  out.push(t.pt);
  return out;
}

/** 折线长度 */
function polyLen(pts) {
  let s = 0;
  for (let i = 1; i < pts.length; i++) {
    s += haversine(pts[i-1][0], pts[i-1][1], pts[i][0], pts[i][1]);
  }
  return s;
}

/** 节点坐标 -> 地名（只有地标最近的那个节点才有名字），调试图层用 */
const NODE_NAME_AT = (() => {
  const m = {};
  for (const p of Object.values(CAMPUS_GRAPH.nodes)) {
    if (p.name) m[p.lng.toFixed(6) + "," + p.lat.toFixed(6)] = p.name;
  }
  return m;
})();

/**
 * 把一条折线翻译成文字指引。
 *
 * 做法：对每个地标，求它到这条折线的**最短距离**与对应的里程位置；
 * 距离在 LANDMARK_TOL 内就算「途中经过」，按里程排好序，就得到
 * 「图书馆 -> 游泳馆 -> 正德楼」这样的途经点序列，以及两两之间的距离。
 *
 * 为什么不按「节点的名字」来：路网节点大多是无名的路口，而地标本体
 * 又都在路边几十米处，一个地标会同时覆盖好几个节点（或一个都盖不到）。
 * 直接量「路线到地标的距离」既准又稳，还顺便把地标本体算进了指引里。
 *
 * @returns {{nodeNames:string[], legs:Array<{from:string,to:string,meters:number}>}}
 */
function buildLegs(points) {
  // 每个折线顶点对应的累计里程
  const cumAt = [0];
  for (let i = 1; i < points.length; i++) {
    cumAt.push(cumAt[i - 1]
      + haversine(points[i - 1][0], points[i - 1][1], points[i][0], points[i][1]));
  }

  const hits = [];
  for (const L of CAMPUS_LANDMARKS) {
    let best = Infinity, at = 0;
    for (let i = 1; i < points.length; i++) {
      const pr = projectToSeg(L.lng, L.lat, points[i - 1], points[i]);
      if (pr.d < best) {
        best = pr.d;
        at = cumAt[i - 1] + polyLen([points[i - 1], pr.pt]);
      }
    }
    if (best <= LANDMARK_TOL) hits.push({ name: L.name, at, d: best });
  }
  hits.sort((a, b) => a.at - b.at);

  // 相邻两个地标挨得太近（同一处路口）时只留更近的那个，避免「经 博文楼 到 正德楼」这种噪声
  const kept = [];
  for (const h of hits) {
    const prev = kept[kept.length - 1];
    if (prev && h.at - prev.at < 25 && prev.d <= h.d) continue;
    if (prev && h.at - prev.at < 25 && prev.d > h.d) { kept.pop(); }
    kept.push(h);
  }

  const nodeNames = kept.map(h => h.name);
  const legs = [];
  for (let i = 1; i < kept.length; i++) {
    legs.push({
      from: kept[i - 1].name,
      to: kept[i].name,
      meters: Math.round(kept[i].at - kept[i - 1].at),
    });
  }
  return { nodeNames, legs };
}

/** 组装返回结构 */
function pack(points) {
  const legs = buildLegs(points);
  return {
    points: points.map(p => [p[0], p[1]]),
    meters: Math.round(polyLen(points)),
    nodeNames: legs.nodeNames,
    legs: legs.legs,
  };
}

/**
 * 列出「可以接受」的若干条吸附路（按离目标点远近排序）。
 *
 * 为什么不是只取最近的那一条：楼宇本体常常离两条路都差不多远，而
 * **最近的那条不一定让总路线最短**。例如正德楼：西侧主干道近 30 米、
 * 东侧路口近 42 米，但走东侧路口能少绕 40 米 —— 取最近反而要「走过头
 * 再折回来」。所以这里把「和最近那条差不多近（+20 米内）」的前 3 条
 * 都当候选，交给调用方各算一遍再取总里程最短的。
 *
 * @returns {Array<{edgeIdx:number, segIdx:number, pt:number[], d:number, t:number}>}
 */
function candidateSnaps(lng, lat, maxSnap) {
  const all = [];
  CAMPUS_GRAPH.edges.forEach((e, ei) => {
    const pts = edgePoints(e);
    let best = null;
    for (let i = 1; i < pts.length; i++) {
      const pr = projectToSeg(lng, lat, pts[i - 1], pts[i]);
      if (!best || pr.d < best.d) {
        best = { edgeIdx: ei, segIdx: i, pt: pr.pt, d: pr.d, t: pr.t };
      }
    }
    if (best) all.push(best);
  });
  all.sort((a, b) => a.d - b.d);
  if (!all.length || all[0].d > maxSnap) return [];
  const cut = all[0].d + 20;
  return all.filter(x => x.d <= cut).slice(0, 3);
}

/** 用给定的吸附点算一条路线（同边直达 / 走节点 + Dijkstra） */
function routeWithSnaps(from, to, f, t) {
  const fe = CAMPUS_GRAPH.edges[f.edgeIdx];
  const te = CAMPUS_GRAPH.edges[t.edgeIdx];

  if (f.edgeIdx === t.edgeIdx) {
    const fPts = edgePoints(fe);
    const direct = [[from[0], from[1]], ...slicePoly(fPts, f, t), [to[0], to[1]]];
    const viaEnd = routeViaNodes(from, to, f, t, fe, te);
    if (!viaEnd || polyLen(direct) <= viaEnd.meters) return pack(direct);
    return viaEnd;
  }
  return routeViaNodes(from, to, f, t, fe, te);
}

/**
 * 校内路线规划主入口：把任意两个校内坐标接到路网上算最短路。
 *
 * 起终点先**投影到最近的道路段**（而不是最近的节点）—— 楼门口、路边、
 * 操场边、GPS 偏移点都能自然走上路网，画出来就是「灰虚线接入 + 蓝实线主路」。
 * 每端各留几个「差不多近」的候选路，两两组合取**总里程最短**的那条。
 *
 * @param {[number,number]} from [lng, lat]
 * @param {[number,number]} to   [lng, lat]
 * @param {number} [maxSnap=120] 起终点允许离最近道路段的最大距离（米），
 *                               超过说明这个点路网覆盖不到，返回 null 走高德
 * @returns {null | {points:number[][], meters:number, nodeNames:string[],
 *                   legs:Array<{from:string,to:string,meters:number}>}}
 */
function planCampusRoute(from, to, maxSnap = 120) {
  if (!inCampus(from[0], from[1]) || !inCampus(to[0], to[1])) return null;

  const F = candidateSnaps(from[0], from[1], maxSnap);
  const T = candidateSnaps(to[0], to[1], maxSnap);
  if (!F.length || !T.length) return null;

  let best = null;
  for (const f of F) {
    for (const t of T) {
      const r = routeWithSnaps(from, to, f, t);
      if (r && (!best || r.meters < best.meters)) best = r;
    }
  }
  return best;
}

/** 经由所在边端点 + Dijkstra 的路线（内部函数） */
function routeViaNodes(from, to, f, t, fe, te) {
  const a1 = fe[0], b1 = fe[1], a2 = te[0], b2 = te[1];
  const fPts = edgePoints(fe), tPts = edgePoints(te);

  // 投影点沿所在边到两端的部分折线
  const fToApts = [f.pt, ...fPts.slice(0, f.segIdx).reverse()]; // pt -> ... -> a1
  const fToBpts = [f.pt, ...fPts.slice(f.segIdx)];              // pt -> ... -> b1
  const tToApts = [t.pt, ...tPts.slice(0, t.segIdx).reverse()]; // pt -> ... -> a2
  const tToBpts = [t.pt, ...tPts.slice(t.segIdx)];              // pt -> ... -> b2

  // 临时邻接表：虚拟节点 F/T 挂到所在边的两端（每项带定向折线）
  const adj = Object.assign({}, ADJ);
  adj.F = [
    { to: a1, edge: fe, len: polyLen(fToApts), pts: fToApts },
    { to: b1, edge: fe, len: polyLen(fToBpts), pts: fToBpts },
  ];
  adj[a1] = [{ to: "F", edge: fe, len: polyLen(fToApts), pts: fToApts.slice().reverse() }, ...ADJ[a1]];
  adj[b1] = [{ to: "F", edge: fe, len: polyLen(fToBpts), pts: fToBpts.slice().reverse() }, ...ADJ[b1]];
  adj.T = [
    { to: a2, edge: te, len: polyLen(tToApts), pts: tToApts },
    { to: b2, edge: te, len: polyLen(tToBpts), pts: tToBpts },
  ];
  adj[a2] = [{ to: "T", edge: te, len: polyLen(tToApts), pts: tToApts.slice().reverse() }, ...ADJ[a2]];
  adj[b2] = [{ to: "T", edge: te, len: polyLen(tToBpts), pts: tToBpts.slice().reverse() }, ...ADJ[b2]];

  const d = dijkstra("F", "T", adj);
  if (!d) return null;

  // 完整折线：from -> 逐段按 nodePath 取定向折线 -> to
  const points = [[from[0], from[1]]];
  const np = d.nodePath;
  for (let i = 0; i < np.length - 1; i++) {
    const u = np[i], v = np[i + 1];
    const ent = (adj[u] || []).find(x => x.to === v);
    const seg = ent && ent.pts ? ent.pts : [];
    for (const pt of seg) {
      const last = points[points.length - 1];
      if (pt[0] !== last[0] || pt[1] !== last[1]) points.push(pt);
    }
  }
  points.push([to[0], to[1]]);
  return pack(points);
}
